def generate_with_gemini(api_key: str, prompt: str) -> Optional[str]:
    """Generates text via Google Gemini API using google.genai SDK or direct REST fallback."""
    # Attempt 1: Using modern official google.genai SDK
    try:
        from google import genai
        client = genai.Client(api_key=api_key)
        # Try gemini-2.5-flash or gemini-1.5-flash
        for model_name in ["gemini-2.5-flash", "gemini-1.5-flash", "gemini-1.5-pro"]:
            try:
                response = client.models.generate_content(
                    model=model_name,
                    contents=prompt,
                )
                if response and response.text:
                    return response.text.strip().strip('"').strip("'")
            except Exception:
                continue
    except ImportError:
        pass

    # Attempt 2: Direct REST API call (Universal, zero dependency conflicts)
    try:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key={api_key}"
        payload = {
            "contents": [{"parts": [{"text": prompt}]}]
        }
        res = requests.post(url, json=payload, timeout=12)
        if res.status_code == 200:
            data = res.json()
            candidates = data.get("candidates", [])
            if candidates:
                parts = candidates[0].get("content", {}).get("parts", [])
                if parts:
                    return parts[0].get("text", "").strip().strip('"').strip("'")
    except Exception:
        pass

    return None


def generate_with_openai(api_key: str, prompt: str) -> Optional[str]:
    """Generates text via OpenAI API using official openai SDK or REST."""
    try:
        from openai import OpenAI
        client = OpenAI(api_key=api_key)
        response = client.chat.completions.create(
            model="gpt-4o-mini",
            messages=[
                {"role": "system", "content": "You are an inspiring personal assistant agent."},
                {"role": "user", "content": prompt},
            ],
            max_tokens=80,
            temperature=0.7,
        )
        if response.choices and response.choices[0].message.content:
            return response.choices[0].message.content.strip().strip('"').strip("'")
    except Exception:
        pass

    # Direct REST fallback for OpenAI
    try:
        headers = {
            "Authorization": f"Bearer {api_key}",
            "Content-Type": "application/json",
        }
        payload = {
            "model": "gpt-4o-mini",
            "messages": [{"role": "user", "content": prompt}],
            "max_tokens": 80,
        }
        res = requests.post("https://api.openai.com/v1/chat/completions", headers=headers, json=payload, timeout=12)
        if res.status_code == 200:
            data = res.json()
            return data["choices"][0]["message"]["content"].strip().strip('"').strip("'")
    except Exception:
        pass

    return None


def get_motivational_quote(
    preferred_provider: Optional[str] = None,
    api_key: Optional[str] = None,
    prompt: str = "Generate a short, punchy motivational quote (1-2 sentences) for an AI developer building personal assistant agents."
) -> Dict[str, Any]:
    """
    Generates or retrieves a motivational quote for the personal assistant agent.

    Args:
        preferred_provider: 'gemini', 'openai', or None (auto-detect based on available keys).
        api_key: Explicit API key if not set in environment.
        prompt: Custom generation prompt.

    Returns:
        Dict with keys: success, provider, model, quote, mode ('live_api' or 'curated_fallback'), message.
    """
    gemini_key = api_key if preferred_provider == "gemini" else (
        os.getenv("GEMINI_API_KEY") or os.getenv("GOOGLE_API_KEY") or (api_key if not preferred_provider else None)
    )
    openai_key = api_key if preferred_provider == "openai" else (
        os.getenv("OPENAI_API_KEY") or (api_key if preferred_provider == "openai" else None)
    )

    # Decision tree based on user preference and key availability
    chosen_provider = None
    if preferred_provider == "gemini" and gemini_key:
        chosen_provider = "gemini"
    elif preferred_provider == "openai" and openai_key:
        chosen_provider = "openai"
    elif gemini_key:
        chosen_provider = "gemini"
    elif openai_key:
        chosen_provider = "openai"

    # Attempt live API call if credentials exist
    if chosen_provider == "gemini" and gemini_key:
        quote_text = generate_with_gemini(gemini_key, prompt)
        if quote_text:
            return {
                "success": True,
                "provider": "Google Gemini",
                "model": "gemini-2.5-flash / gemini-1.5-flash",
                "mode": "live_api",
                "quote": quote_text,
                "message": "Generated live via Google Gemini API",
            }

    if chosen_provider == "openai" and openai_key:
        quote_text = generate_with_openai(openai_key, prompt)
        if quote_text:
            return {
                "success": True,
                "provider": "OpenAI",
                "model": "gpt-4o-mini",
                "mode": "live_api",
                "quote": quote_text,
                "message": "Generated live via OpenAI API",
            }

    # Fallback mode (Per assignment hint: "If you don't have API access, use ChatGPT to generate sample code for this task and adapt it for your script.")
    picked = random.choice(CURATED_AI_QUOTES)
    return {
        "success": True,
        "provider": "Curated AI Engine (ChatGPT Adapted)",
        "model": "gpt-4o-mini-adapted",
        "mode": "curated_fallback",
        "quote": picked["quote"],
        "author": picked["author"],
        "theme": picked["theme"],
        "message": (
            "ℹ️  [Notice] Live API key not detected in environment.\n"
            "    To activate live LLM generation:\n"
            "    • Gemini: set GEMINI_API_KEY=\"AIza...\" (Windows) or export GEMINI_API_KEY=\"AIza...\"\n"
            "    • OpenAI: set OPENAI_API_KEY=\"sk-...\" (Windows) or export OPENAI_API_KEY=\"sk-...\"\n"
            "    Displaying curated quote generated for this script:"
        ),
    }


def display_quote(quote_data: Dict[str, Any]) -> None:
    """Displays the motivational quote in an elegant card format."""
    print("=" * 65)
    print(" 💡  PERSONAL ASSISTANT: MOTIVATIONAL QUOTE OF THE DAY")
    print("=" * 65)

    if quote_data.get("message"):
        print(quote_data["message"])
        print("-" * 65)

    quote = quote_data.get("quote", "")
    provider = quote_data.get("provider", "AI Assistant")
    model = quote_data.get("model", "Default")
    mode = quote_data.get("mode", "curated_fallback")
    author = quote_data.get("author")

    print(f"\n  \"{quote}\"\n")
    if author:
        print(f"  — {author}")
    print("-" * 65)
    print(f"🤖 Generated by : {provider} ({model})")
    print(f"⚡ Mode         : {'🟢 Live API Call' if mode == 'live_api' else '🟡 Adapted AI Sample (Zero-Cost / Offline)'}")
    print("=" * 65)


def main():
    """Main execution point."""
    provider_arg = sys.argv[1].lower() if len(sys.argv) > 1 else None
    key_arg = sys.argv[2] if len(sys.argv) > 2 else None

    print("\n[Motivational Agent] Requesting daily inspiration...")
    quote_result = get_motivational_quote(preferred_provider=provider_arg, api_key=key_arg)
    display_quote(quote_result)


if __name__ == "__main__":
    main()
